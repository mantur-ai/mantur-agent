import assert from 'node:assert/strict'
import { mkdtemp, mkdir, writeFile, readFile, readdir, rm, symlink } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { createHash } from 'node:crypto'
import { test } from 'node:test'
import beforePack from './package-symbols.mjs'

async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'desktop-symbol-test-'))
  t.after(() => rm(root, { recursive: true, force: true }))
  await mkdir(join(root, 'lib/types'), { recursive: true })
  await mkdir(join(root, 'src'))
  await writeFile(join(root, 'src/main.ts'), 'export const value = 1\n')
  await writeFile(join(root, 'lib/types/main.js'), 'export const value = 1;\n')
  await writeFile(join(root, 'lib/types/main.js.map'), JSON.stringify({ version: 3, sources: ['../../src/main.ts'], mappings: '' }))
  await writeFile(join(root, 'lib/LICENSE'), 'license')
  const context = { outDir: join(root, 'dist'), arch: 3, electronPlatformName: 'darwin', packager: { info: { appDir: root }, appInfo: { version: '1.2.3' } } }
  return { root, context }
}

test('archives matching symbols, generated bytes and dirty source content without mutating input', async t => {
  const { root, context } = await fixture(t)
  await beforePack(context)
  const [directory] = await readdir(join(root, 'dist/symbols'))
  const archive = join(root, 'dist/symbols', directory)
  const manifest = JSON.parse(await readFile(join(archive, 'manifest.json'), 'utf8'))
  assert.equal(manifest.applicationVersion, '1.2.3')
  assert.equal(manifest.entries.length, 1)
  for (const entry of [manifest.entries[0].map, manifest.entries[0].generated, ...manifest.entries[0].sources]) {
    const original = await readFile(join(root, entry.path))
    assert.deepEqual(await readFile(join(archive, entry.path)), original)
    assert.equal(entry.sha256, createHash('sha256').update(original).digest('hex'))
  }
  assert.equal(await readFile(join(root, 'lib/LICENSE'), 'utf8'), 'license')
})

test('rejects missing original sources before packaging', async t => {
  const { root, context } = await fixture(t)
  await rm(join(root, 'src/main.ts'))
  await assert.rejects(beforePack(context), /ENOENT/)
  assert.ok(await readFile(join(root, 'lib/types/main.js.map')))
})

test('rejects a source location outside the application', async t => {
  const { root, context } = await fixture(t)
  await writeFile(join(root, 'lib/types/main.js.map'), JSON.stringify({ version: 3, sources: [import.meta.filename] }))
  await assert.rejects(beforePack(context), /escapes/)
})

test('rejects symlinks instead of backing up a different release input', async t => {
  const { root, context } = await fixture(t)
  await symlink(join(root, 'src'), join(root, 'lib/linked'))
  await assert.rejects(beforePack(context), /symbolic link/)
})

test('rejects a backup location that cannot be created', async t => {
  const { root, context } = await fixture(t)
  await mkdir(context.outDir)
  await writeFile(join(context.outDir, 'symbols'), 'occupied')
  await assert.rejects(beforePack(context))
  assert.ok(await readFile(join(root, 'lib/types/main.js.map')))
})

test('builder filters only compiler maps and retains executable and offline files', async t => {
  const { root } = await fixture(t)
  const { createRequire } = await import('node:module')
  const desktopRequire = createRequire(new URL('../package.json', import.meta.url))
  const builderRequire = createRequire(desktopRequire.resolve('electron-builder/package.json'))
  const { FileMatcher } = builderRequire('app-builder-lib/out/fileMatcher.js')
  const config = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8')).build
  const filter = new FileMatcher(root, join(root, 'output'), value => value, config.files).createFilter()
  const ordinaryFile = { isDirectory: () => false }
  for (const path of ['lib/main.js', 'lib/LICENSE', 'lib/source.ts', 'lib/SOURCE_OFFER.txt', 'lib/runtime.map', 'resources/offline.wasm', 'resources/atlas.js.map']) {
    assert.equal(filter(join(root, path), ordinaryFile), true, path)
  }
  for (const path of ['lib/main.js.map', 'lib/types/main.js.map', 'lib/types/main.d.ts.map']) {
    assert.equal(filter(join(root, path), ordinaryFile), false, path)
  }
  assert.equal(config.beforePack, './scripts/package-symbols.mjs')
  assert.equal(config.extraResources.some(resource => resource.filter !== undefined), false)
})
